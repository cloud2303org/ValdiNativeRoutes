import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test from 'node:test';
import vm from 'node:vm';
import ts from 'typescript';
import { unpack } from './archive';
import { root } from './pipeline';
import { compileRuntimeModule, type RuntimeModuleSpec } from './runtime-module';

const golden = JSON.parse(readFileSync(new URL('./runtime-native-golden.json', import.meta.url), 'utf8'));
const iosNames: Record<string, string> = {
  client_sql: 'SCCClientSQL', coreutils: 'SCCCoreutils', drawing: 'SCCDrawing',
  jasmine: 'SCCJasmine', source_map: 'SCCSourceMap', valdi_core: 'SCCValdiCore', valdi_tsx: 'SCCValdiTsx',
};

test('all seven real runtime modules retain the pinned Swift compiler native ABI and produce usable Node assets', async t => {
  // The hashes retain their original compiler provenance across source-only
  // fork cleanups. Actual generated bytes below must still match all 44 files.
  const temporary = mkdtempSync(path.join(tmpdir(), 'runtime-module-test-'));
  t.after(() => rmSync(temporary, { recursive: true, force: true }));
  const upstream = process.env.VALDI_SOURCE_ROOT ?? path.join(root, 'valdi/bazel-valdi/external/valdi+');
  for (const [name, iosModuleName] of Object.entries(iosNames)) {
    await t.test(name, async () => {
      const moduleDirectory = path.join(upstream, 'src/valdi_modules/src/valdi', name);
      const sources = ['src', 'types'].flatMap(dir => ts.sys.readDirectory(path.join(moduleDirectory, dir), ['.ts', '.tsx', '.js']));
      const relative = Object.keys(golden.files).filter(file => file.startsWith(name + '/')).map(file => file.slice(name.length + 1));
      relative.push(`android/debug/assets/${name}.valdimodule`, `android/release/assets/${name}.valdimodule`,
        `android/debug/assets/${name}.map.json`, `.valdi_build/compile/typescript/dumped_symbols/${name}/compilation-metadata.json`);
      relative.push(...sources.filter(file => /\.(ts|tsx)$/.test(file) && !file.endsWith('.d.ts')).map(file =>
        `.valdi_build/compile/typescript/output/${name}/${path.relative(moduleDirectory, file).replace(/\.tsx?$/, '.d.ts')}`));
      const spec: RuntimeModuleSpec = {
        name, moduleDirectory, sources, outputs: relative.map(relative => ({ relative, path: path.join(temporary, name, relative), directory: false })),
        dependencies: Object.keys(iosNames).map(module_name => ({ module_name, module_path: '', module_content: '' })),
        iosModuleName, iosClassPrefix: '__valdi_unset_ios_class_prefix__', androidClassPath: `com.snap.modules.${name}`,
        disableAnnotations: name === 'jasmine', asyncStrictMode: false, compilationMode: name === 'jasmine' ? 'js' : 'js_bytecode',
      };
      await compileRuntimeModule(spec);
      for (const [file, expected] of Object.entries(golden.files)) {
        if (!file.startsWith(name + '/')) continue;
        assert.equal(createHash('sha256').update(readFileSync(path.join(temporary, file))).digest('hex'), expected, file);
      }
      const debug = unpack(readFileSync(path.join(temporary, name, 'android/debug/assets', name + '.valdimodule')));
      const release = unpack(readFileSync(path.join(temporary, name, 'android/release/assets', name + '.valdimodule')));
      assert.ok(debug.has('hash'));
      assert.ok(release.has('hash'));
      assert.ok(![...release.keys()].some(file => file.startsWith('test/') || file.includes('.spec.')));
      for (const [file, content] of release) {
        if (!file.endsWith('.js')) continue;
        if (name !== 'jasmine') assert.equal(content.readUInt32LE(0), 0x0100c634, file);
      }
      if (name === 'valdi_core') {
        for (const file of ['Init', 'Long', 'Promise', 'tslib']) assert.ok(debug.has(`src/${file}.js`), file);
        assert.match(debug.get('src/Init.js')!.toString(), /moduleLoader/);
        // Init's root evaluator can load only tslib until ModuleLoader.create
        // installs normal require. A Rolldown shared chunk here crashes startup.
        const exports: Record<string, unknown> = {};
        const requireRoot = (id: string) => {
          assert.equal(id, 'tslib', 'bootstrap cannot load a shared chunk');
          return {};
        };
        vm.runInNewContext(`(function(require, module, exports) {${debug.get('src/ModuleLoader.js')!.toString()}\n})`)(requireRoot, { exports }, exports);
        assert.equal(typeof exports.create, 'function');
        assert.ok(![...debug.keys()].some(file => file.startsWith('chunks/')));
      }
      assert.ok(JSON.parse(readFileSync(path.join(temporary, name, `.valdi_build/compile/typescript/dumped_symbols/${name}/compilation-metadata.json`), 'utf8')).compiler === 'node-valdi-rolldown');
    });
  }
});
