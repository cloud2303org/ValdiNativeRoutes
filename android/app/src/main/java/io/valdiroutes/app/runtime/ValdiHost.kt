/** One Valdi runtime for the whole app; every page is a root view inside it. */
object ValdiHost {
    private lateinit var runtimeManager: ValdiRuntimeManager
    private val main = Handler(Looper.getMainLooper())

    fun init(app: Application) {
        // Named after the valdi_exported_library() target.
        StartupTrace.section("runtime.load_library") { System.loadLibrary("valdi_runtime") }
        // Module library is built by our Node/Bazel rules; no upstream annotation processor is needed.
        StartupTrace.section("runtime.generated_factories.register") {
            io.valdiroutes.generated.ValdiNativeModules.registerFactories(app)
            AppNativeModules.register(app, navigationHost)
        }
        // SupportValdiRuntimeManager.createWithSupportLibs, with the over-the-air module provider (ValdiOta.kt).
        StartupTrace.section("runtime.context_factories.register") {
            ModuleFactoryRegistry.registerModuleFactoriesFromContext(app)
        }
        // Preserve argument evaluation order: tweaks, then OTA selection, then manager construction.
        val tweaks = StartupTrace.section("runtime.tweaks.create") { ValdiTweaks() }
        val moduleProvider = StartupTrace.section("ota.provider.select") { ValdiOta.start(app) }
        runtimeManager = StartupTrace.section("runtime.manager.create") {
            ValdiRuntimeManager(app, tweaks = tweaks, customModuleProvider = moduleProvider)
        }
        // Only valdi-video:// session URLs use this loader. The generated native module factory and loader
        // explicitly share one resource registry; ordinary images and media URL resolution stay independent.
        StartupTrace.section("runtime.video_asset_loader.register") {
            runtimeManager.registerAssetLoader(videoHost.loader)
        }
        StartupTrace.section("runtime.context_global_binders.register") {
            runtimeManager.registerGlobalAttributesBindersFromContext(app)
        }
        StartupTrace.section("runtime.generated_view_binders.register") {
            io.valdiroutes.generated.ValdiNativeModules.registerViewBinders(app, runtimeManager)
        }
        StartupTrace.section("runtime.support.configure") {
            SupportValdiRuntimeManager.configureSupportLibs(runtimeManager)
        }
        StartupTrace.section("runtime.initial_dark_mode") { notifyDarkMode(app.resources.configuration) }
        // The <custom-view> wheels (WheelViews.kt). Valdi's @RegisterAttributesBinder list is generated by its own
        // Android build, not by Gradle, so they are registered here.
        StartupTrace.section("runtime.wheel_binders.register") {
            runtimeManager.registerGlobalAttributesBinder(ValdiWheelBinder(ColumnWheelView::class.java))
            runtimeManager.registerGlobalAttributesBinder(ValdiWheelBinder(TimeWheelView::class.java))
            runtimeManager.registerGlobalAttributesBinder(ValdiWheelBinder(TreeWheelView::class.java))
        }
        val scopeRequest = StartupTrace.start("hosts.request_to_js_callback")
        StartupTrace.section("hosts.createScopedJSRuntime.call") {
            runtimeManager.mainRuntime.createScopedJSRuntime("hosts") { js ->
                StartupTrace.finish(scopeRequest)
                try {
                    StartupTrace.section("hosts.js_callback") {
                        hostScope = js
                        // App-wide objects (the SQLite connection, api, the router) belong in this retained scope, not in a page.
                        val debug = (app.applicationInfo.flags and ApplicationInfo.FLAG_DEBUGGABLE) != 0
                        val startApp = StartupTrace.section("hosts.StartApp.resolve") { StartApp.create(js) }
                        val declaration = StartupTrace.section("hosts.StartApp.invoke") {
                            startApp.invoke(debug)
                        }
                        // Includes lazy bridge property decoding and the existing native route validation.
                        val table = StartupTrace.section("routes.decode_and_validate") { RouteTable.from(declaration) }
                        StartupTrace.mark("routes.ready_on_js")
                        thread(name = "ValdiOta") { ValdiOta.checkForUpdate() }
                        val mainDispatch = StartupTrace.start("routes.post_to_main_callback")
                        main.post {
                            StartupTrace.finish(mainDispatch)
                            StartupTrace.section("routes.deliver_on_main") {
                                started = table
                                val callbacks = waiting.toList()
                                waiting.clear()
                                callbacks.forEach { it(Result.success(table)) }
                            }
                        }
                    }
                } catch (error: Exception) {
                    main.post {
                        startupFailure = error
                        val callbacks = waiting.toList()
                        waiting.clear()
                        callbacks.forEach { it(Result.failure(error)) }
                    }
                }
            }
        }
    }

    private var started: RouteTable? = null
    private var startupFailure: Exception? = null
    private val waiting = mutableListOf<(Result<RouteTable>) -> Unit>()
    private val contentRevisions = WeakHashMap<ValdiRootView, Long>()

    /**
     * The system appearance, for Device.observeDarkMode (theme.ts): Valdi reads it on iOS but not here. At startup,
     * and from MainActivity.onConfigurationChanged (uiMode is in its configChanges, so it isn't recreated).
     */
    fun notifyDarkMode(configuration: Configuration) {
        val dark = (configuration.uiMode and Configuration.UI_MODE_NIGHT_MASK) == Configuration.UI_MODE_NIGHT_YES
        // The first call from init forces the lazy main runtime; keep that access in its original position.
        val runtime = StartupTrace.section("runtime.mainRuntime.resolve", "caller=notifyDarkMode") {
            runtimeManager.mainRuntime
        }
        StartupTrace.section("runtime.dark_mode.getNativeModules.call") {
            runtime.getNativeModules { it.deviceModule.notifyDarkModeChanged(dark) }
        }
    }

    /** The navigator JS drives: the activity's, while it exists. */
    var navigator: Navigator? = null

    /** `router` (routes.ts) lands here on the JS thread; the navigator lives on the main thread. */
    private val navigationHost = NavigationHost(
        { route, params, navigation ->
            onNavigator { it.open(route, params, navigation) }
        },
        { route, params, navigation, onResult ->
            onNavigator {
                it.open(route, params, navigation, onResult)
            }
        },
        { route, params, navigation -> onNavigator { it.replace(route, params, navigation) } },
        { delta -> onNavigator { it.back(delta.toInt()) } },
        { onNavigator { it.popToRoot() } },
        { route, params -> onNavigator { it.reset(route, params) } },
        { tab -> onNavigator { it.switchTab(tab) } },
        { style -> onNavigator { it.statusBarStyle = style } },
        { done -> main.post { done(navigator?.currentPages() ?: emptyList()) } },
        { declaration ->
            val table = RouteTable.from(declaration)
            main.post {
                navigator?.reloadRoutes(table)
                started = table.withRoot(navigator?.stack?.firstOrNull()?.route ?: table.root)
            }
        },
    )

    private fun onNavigator(action: (Navigator) -> Unit) {
        main.post { navigator?.let(action) }
    }

    /**
     * Native functions handed to JS belong to the scoped runtime they were passed through, and are disposed with it
     * ("Cannot unwrap native function … reference was disposed"). JS keeps the hosts for the app's lifetime, so
     * their scope does too. @Keep: the field is only written, and R8 would remove it in release, letting the scope be
     * collected.
     */
    @Keep
    private var hostScope: ValdiScopedJSRuntime? = null

    /** Runtime permissions for permissions/index.ts; the activity lends it the permission prompt. */
    val permissionHost: PermissionHostImpl
        get() = PermissionModuleFactoryImpl.requireHost()

    val videoHost: VideoHostImpl
        get() = VideoModuleFactoryImpl.requireHost()

    /** The route table, tab bar and first page, from startApp (app.ts); on the main thread, once JS has started. */
    fun start(onFailure: (Exception) -> Unit, completion: (RouteTable) -> Unit): () -> Unit {
        val callback: (Result<RouteTable>) -> Unit = { result ->
            result.fold(completion) { onFailure(it as? Exception ?: RuntimeException(it)) }
        }
        when {
            startupFailure != null -> onFailure(requireNotNull(startupFailure))
            started != null -> completion(requireNotNull(started))
            else -> waiting.add(callback)
        }
        return { waiting.remove(callback) }
    }

    internal fun contentRevision(root: ValdiRootView): Long = contentRevisions[root] ?: 0L

    internal fun requestInitialContentDraw(root: ValdiRootView, ready: (Exception?) -> Unit) {
        root.getValdiContext { context ->
            // This fences JS root creation, not content rendering or Android drawing.
            context.waitUntilAllUpdatesCompleted {
                val scope = hostScope
                if (scope == null) {
                    ready(IllegalStateException("App startup scope is unavailable"))
                    return@waitUntilAllUpdatesCompleted
                }
                scope.runOnJsThread("initial-content-draw") {
                    if (!context.isDestroyed()) {
                        try {
                            val accepted = RequestInitialContentDraw.create(scope)
                                .invoke(context.contextId.toString()) { ready(null) }
                            if (!accepted && !context.isDestroyed()) {
                                ready(IllegalStateException("Initial content renderer is unavailable"))
                            }
                        } catch (error: Exception) {
                            ready(error)
                        }
                    }
                }
            }
        }
    }

    fun createPage(context: Context, entry: PageEntry, insets: Insets, navigator: Navigator): ValdiRootView {
        val details = StartupTrace.pageDetails("page", entry.id, entry.route)
        return StartupTrace.section("page.create", details) {
            val component = requireNotNull(entry.definition.component) { "${entry.route} is not a Valdi page" }
            val rootView = StartupTrace.section("page.root_view.create", details) {
                StartupTrace.rootView(context, details).apply {
                    // The root view is focusable and fills the screen, so outside touch mode (hardware keys, D-pad) the
                    // system's focus highlight would grey out the whole page.
                    defaultFocusHighlightEnabled = false
                    setRetainsLayoutSpecsOnInvalidateLayout(true)
                }
            }
            val completion = StartupTrace.renderCompletion(rootView, details)
            StartupTrace.section("page.inflateViewAsync.call", details) {
                runtimeManager.mainRuntime.inflateViewAsync(
                    rootView, component, viewModel(entry, insets), pageContext(entry, navigator), null, completion, null,
                )
            }
            rootView
        }
    }

    fun updateInsets(entry: PageEntry, insets: Insets) {
        entry.rootView?.let { root ->
            root.setViewModelUntyped(viewModel(entry, insets))
            contentRevisions[root] = contentRevision(root) + 1
        }
    }

    internal fun createTabBar(
        context: Context, shell: PageEntry, bar: TabBar, selected: String, safeAreaBottom: Double, navigator: Navigator,
    ): CustomTabBar {
        val selection = TabBarSelection(bar.tabs.map { it.route }) { navigator.selectTab(shell, it) }
        val tabContext = TabBarContext { route -> main.post { selection.select(route) } }
        val details = StartupTrace.pageDetails("tab_bar", shell.id, shell.route)
        val root = StartupTrace.rootView(context, details).apply {
            defaultFocusHighlightEnabled = false
            isFocusable = false
            isFocusableInTouchMode = false
            setRetainsLayoutSpecsOnInvalidateLayout(true)
            // The legacy dispatcher returns false for empty space; the newer dispatcher always consumes DOWN.
            useNewMultiTouchExperience = false
        }
        val owner = CustomTabBar(root, tabContext, selection)
        val completion = StartupTrace.renderCompletion(root, details)
        StartupTrace.section("tab_bar.inflateViewAsync.call", details) {
            runtimeManager.mainRuntime.inflateViewAsync(
                root, requireNotNull(bar.component), TabBarViewModel(bar.tabs, selected, safeAreaBottom), tabContext,
                null, completion, ValdiContextConfiguration(renderBackend = RenderBackend.ANDROID),
            )
        }
        return owner
    }

    internal fun updateTabBar(owner: CustomTabBar, bar: TabBar, selected: String, safeAreaBottom: Double) {
        owner.update(selected, safeAreaBottom) {
            owner.rootView.setViewModelUntyped(TabBarViewModel(bar.tabs, selected, safeAreaBottom))
            contentRevisions[owner.rootView] = contentRevision(owner.rootView) + 1
        }
    }

    /** The page's visibility changed (Navigator.updateVisibility); a page without its view yet gets it on creation. */
    fun updateVisibility(entry: PageEntry) {
        val insets = entry.appliedInsets ?: return
        entry.rootView?.let { root ->
            root.setViewModelUntyped(viewModel(entry, insets))
            contentRevisions[root] = contentRevision(root) + 1
        }
    }

    private fun viewModel(entry: PageEntry, insets: Insets) = PageViewModel(
        entry.id, entry.route, entry.params, entry.presentation.value,
        PageInsets(insets.top.toDouble(), insets.bottom.toDouble(), insets.left.toDouble(), insets.right.toDouble()),
        entry.visible, entry.visibilityReason,
    )

    // TS calls these on the JS thread; navigation state lives on the main thread. A tab page is not on the stack, so
    // both do nothing for it.
    private fun pageContext(entry: PageEntry, navigator: Navigator) = PageContext(
        { result -> main.post { navigator.finish(entry.id, result) } },
        { main.post { navigator.cancel(entry.id) } },
    )
}
