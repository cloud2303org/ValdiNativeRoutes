import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { generateNativeCode, nativeSourceFiles, type CodegenModule, type NativeCode } from './codegen/index';

export interface CppModulePlan {
  /** Binding requests: all implementation owners plus any explicit roots. */
  roots: string[];
  /** Enabled owners with cpp/src implementations; only these have a :native target. */
  implementationRoots: string[];
  /** Full available catalog, including disabled modules whose parent packages belong to the module workspace. */
  availableModules: string[];
  /** Sorted closure, with direct generated-include edges (cycles are allowed). */
  modules: {
    name: string;
    dependencies: string[];
    /** Paths relative to this module's cpp/generated include root. */
    files: ReadonlyMap<string, string>;
  }[];
}

/** Only implementation sources owned by a module make it a default C++ root. */
export function ownsCppImplementation(moduleDirectory: string): boolean {
  const visit = (directory: string): boolean => existsSync(directory) && readdirSync(directory, { withFileTypes: true })
    .some(entry => entry.isDirectory()
      ? visit(path.join(directory, entry.name))
      : entry.isFile() && /\.(?:cpp|cc|cxx)$/.test(entry.name));
  return visit(path.join(moduleDirectory, 'cpp/src'));
}

/** Inspect both generated headers and sources; TS imports alone do not require C++ bindings. */
export function generatedCppDependencies(name: string, files: ReadonlyMap<string, string>): string[] {
  const dependencies = new Set<string>();
  for (const content of files.values()) {
    for (const match of content.matchAll(/^[ \t]*#[ \t]*include[ \t]+[<"]valdi_modules\/([a-z][a-z0-9_]*)\/\1\.hpp[>"]/gm)) {
      if (match[1] !== name) dependencies.add(match[1]);
    }
  }
  return [...dependencies].sort();
}

/**
 * Plan without writing files or changing the native schema. `modules` is the enabled codegen catalog.
 * `availableModules` includes disabled directories from the root module scan, independently of the C++ closure.
 * Explicit roots add binding requests to all default implementation owners, keeping runtime output complete.
 */
export function planCppModules(options: {
  modules: Record<string, CodegenModule>;
  availableModules?: readonly string[];
  roots?: readonly string[];
  generate?: (target: CodegenModule) => NativeCode;
}): CppModulePlan {
  const { modules, generate = generateNativeCode } = options;
  const available = new Set(options.availableModules ?? Object.keys(modules));
  const implementationRoots = Object.keys(modules)
    .filter(name => ownsCppImplementation(modules[name].module.dir)).sort();
  const roots = [...new Set([
    ...implementationRoots,
    ...(options.roots ?? []),
  ])].sort();
  const planned = new Map<string, CppModulePlan['modules'][number]>();
  const visit = (name: string, from?: string) => {
    if (planned.has(name)) return;
    const target = Object.hasOwn(modules, name) ? modules[name] : undefined;
    if (!target) {
      throw new Error(`C++ ${from ? `dependency "${name}" of "${from}"` : `root "${name}"`} is ${
        available.has(name) ? 'disabled; enable it in package.json valdi.modules' : 'missing from the module catalog'}.`);
    }
    const files = new Map([...nativeSourceFiles(target, generate(target), 'cpp')]
      .filter(([, content]) => content.length > 0));
    const dependencies = generatedCppDependencies(name, files);
    // Memoize before following edges, including back-edges in a cycle.
    planned.set(name, { name, dependencies, files });
    for (const dependency of dependencies) visit(dependency, name);
  };
  for (const name of roots) visit(name);
  return { roots, implementationRoots, availableModules: [...available].sort(),
    modules: [...planned.values()].sort((a, b) => a.name.localeCompare(b.name)) };
}

const moduleId = /^[a-z][a-z0-9_]*$/;
const ownedFiles = (name: string) => ['hpp', 'cpp'].map(extension => `valdi_modules/${name}/${name}.${extension}`);
const generatedPrefix = '# Generated by tools/valdi-rolldown/codegen.ts --cpp-modules-out; do not edit.';
const bindingPackagePrefix = `${generatedPrefix}\n# Binding-only package managed by --cpp-modules-out.\n`;
const bindingPackageBuild = (name: string) => [
  bindingPackagePrefix,
  'load("//bzl/module_cpp:module.bzl", "module_cpp_library")',
  '',
  '# Source globs enable :native automatically when implementations are added.',
  'module_cpp_library(',
  `    module_name = "${name}",`,
  '    srcs = glob(["src/**/*.cpp", "src/**/*.cc", "src/**/*.cxx"], allow_empty = True),',
  '    hdrs = glob(["src/**/*.h", "src/**/*.hpp"], allow_empty = True),',
  ')',
  '',
].join('\n');

/**
 * Synchronize runtime config, bindings and missing C++ packages, preserving handwritten BUILD files and cpp/src.
 * Only marked binding-only packages without implementations can be removed outside the plan.
 * Check mode performs no filesystem mutations.
 */
export function syncCppModules(plan: CppModulePlan, modulesDirectory: string, check = false): string[] {
  const directory = path.resolve(modulesDirectory);
  const expected = new Map<string, string>();
  const available = [...new Set(plan.availableModules)].sort();
  const implementations = [...new Set(plan.implementationRoots)].sort();
  const planned = [...plan.modules].sort((a, b) => a.name.localeCompare(b.name));
  for (const name of [...available, ...plan.roots, ...implementations,
    ...planned.flatMap(module => [module.name, ...module.dependencies])]) {
    if (!moduleId.test(name)) throw new Error(`Invalid C++ module ID "${name}".`);
  }
  const names = new Set(planned.map(module => module.name));
  for (const name of implementations) {
    if (!plan.roots.includes(name) || !names.has(name)) {
      throw new Error(`C++ implementation "${name}" is missing from the planned roots.`);
    }
  }
  for (const module of planned) {
    for (const dependency of module.dependencies) {
      if (!names.has(dependency)) throw new Error(`C++ dependency "${dependency}" of "${module.name}" is not planned.`);
    }
  }
  expected.set(path.join(directory, 'runtime-packages.bazelrc'), [
    generatedPrefix,
    '# Parent module packages belong to the module workspace; nested cpp packages remain available.',
    ...(available.length ? [`common --deleted_packages=${available.map(name => `modules/${name}`).join(',')}`] : []),
    '',
  ].join('\n'));
  expected.set(path.join(directory, 'runtime-cpp.bzl'), [
    generatedPrefix,
    '# Only implementation owners link into the runtime; explicit binding requests remain binding-only.',
    'CPP_IMPLEMENTATIONS = [',
    ...implementations.map(name => `    "//modules/${name}/cpp:native",`),
    ']',
    '',
    'CPP_BINDING_DEPS = {',
    ...planned.flatMap(module => [
      `    "${module.name}": [`,
      ...[...new Set(module.dependencies)].sort().map(name => `        "//modules/${name}/cpp:bindings",`),
      '    ],',
    ]),
    '}',
    '',
  ].join('\n'));
  for (const module of planned) {
    const build = path.join(directory, module.name, 'cpp/BUILD.bazel');
    const existing = existsSync(build) ? readFileSync(build, 'utf8') : undefined;
    if (existing === undefined ? !existsSync(path.join(directory, module.name, 'cpp/BUILD'))
      : existing.startsWith(bindingPackagePrefix)) {
      expected.set(build, bindingPackageBuild(module.name));
    }
    const owned = new Set(ownedFiles(module.name));
    for (const [file, content] of module.files) {
      if (!owned.has(file)) throw new Error(`Unexpected generated C++ output for "${module.name}": ${file}`);
      expected.set(path.join(directory, module.name, 'cpp/generated', file), content);
    }
  }
  const stale = new Set<string>();
  if (existsSync(directory)) {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      if (!entry.isDirectory() || !moduleId.test(entry.name)) continue;
      const build = path.join(directory, entry.name, 'cpp/BUILD.bazel');
      if (!names.has(entry.name) && existsSync(build)
        && readFileSync(build, 'utf8').startsWith(bindingPackagePrefix)
        && !ownsCppImplementation(path.join(directory, entry.name))) {
        stale.add(build);
      }
      for (const file of ownedFiles(entry.name)) {
        const output = path.join(directory, entry.name, 'cpp/generated', file);
        if (!expected.has(output) && existsSync(output)) stale.add(output);
      }
    }
  }
  const changed: string[] = [];
  for (const output of [...new Set([...expected.keys(), ...stale])].sort()) {
    const content = expected.get(output);
    if (content === undefined) {
      changed.push(`${output} (${path.basename(output) === 'BUILD.bazel'
        ? 'stale binding-only C++ package' : 'stale C++ bindings'}; remove)`);
      if (!check) rmSync(output);
    } else if (!existsSync(output) || readFileSync(output, 'utf8') !== content) {
      changed.push(output);
      if (!check) {
        mkdirSync(path.dirname(output), { recursive: true });
        writeFileSync(output, content);
      }
    }
  }
  return changed;
}
