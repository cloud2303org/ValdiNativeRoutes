import { cpSync, existsSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { homedir } from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const args = process.argv.slice(2);
const business = args.includes('--business');
const profile = business ? 'business' : 'smoke';
if (process.platform !== 'darwin') throw new Error('This Harmony build setup currently requires macOS.');
const toolDirectory = path.join(homedir(), 'Library/Huawei');
const tools = process.env.DEVECO_CLI_CLT_PATH ?? (existsSync(toolDirectory)
  ? readdirSync(toolDirectory).sort((a, b) => b.localeCompare(a, undefined, { numeric: true }))
    .map(version => path.join(toolDirectory, version, 'command-line-tools'))
    .find(directory => existsSync(path.join(directory, 'sdk/default/sdk-pkg.json')))
  : undefined);
if (!tools) throw new Error('Set DEVECO_CLI_CLT_PATH to the installed Mac Command Line Tools directory.');
const env = { ...process.env, DEVECO_CLI_CLT_PATH: tools, DEVECO_SDK_HOME: path.join(tools, 'sdk') };
function run(command, args, cwd = root) {
  const result = spawnSync(command, args, { cwd, env, stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}
run(process.execPath, ['scripts/harmony/prepare-runtime.mjs']);
run(process.execPath, ['scripts/harmony/prepare-business.mjs']);
const generated = path.join(root, '.tools/harmony', `${profile}-rawfile`);
const builder = business
  ? ['tools/valdi-rolldown/harmony-business.ts', '--out', generated]
  : ['tools/valdi-rolldown/harmony.ts', path.join(root, '.tools/harmony/upstream'), path.join(generated, 'modules')];
run(process.execPath, ['tools/valdi-rolldown/node_modules/tsx/dist/cli.mjs', ...builder]);
const rawfile = path.join(root, 'harmony/entry/src/main/resources/rawfile');
mkdirSync(rawfile, { recursive: true });
// These directories are generated by the two HBC builders. Replace them together
// so a profile cannot load modules or tab resources left by the other profile.
for (const name of ['modules', 'assets', 'tab-icons', 'valdi', 'build-info.json']) {
  rmSync(path.join(rawfile, name), { recursive: true, force: true });
  if (existsSync(path.join(generated, name))) {
    cpSync(path.join(generated, name), path.join(rawfile, name), { recursive: true });
  }
}
console.log(`Harmony HAP profile: ${profile}`);
run('devecocli', ['build', ...args.filter(arg => arg !== '--business')], path.join(root, 'harmony'));
