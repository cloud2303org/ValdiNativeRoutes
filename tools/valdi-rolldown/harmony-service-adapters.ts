// Adapter-only generator: annotation/model metadata and the canonical C++ type parser.
// Never parses emitted C++, edits the pipeline or writes canonical ABI bindings.
import ts from 'typescript';
import path from 'node:path';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { processAnnotations } from './codegen/ApplyTypeScriptAnnotationsProcessor';
import { dumpAllSymbols } from './codegen/DumpTypeScriptSymbols';
import { CppCodeGenerator, CppCodeGeneratorSingleNamespaceResolver } from './codegen/cpp/CppCodeGenerator';
import { propertyNameAllocatorForCpp } from './codegen/cpp/CppValidation';
import { CppNamespace, cppFullTypeName, type BundleInfo, type ValdiModel } from './codegen/Models';
import type { ValdiModule } from './valdiTs';
export const serviceInputs = [
  { service: 'ble', module: 'bluetooth', host: 'BleHost', file: 'src/BleHost.ts' },
  { service: 'permissions', module: 'app_pages', host: 'PermissionHost', file: 'src/permissions/PermissionHost.ts' },
  { service: 'wifi', module: 'app_pages', host: 'WifiHost', file: 'src/wifi/WifiHost.ts' },
  { service: 'nfc', module: 'app_pages', host: 'NfcHost', file: 'src/nfc/NfcHost.ts' },
] as const;
export function generateServiceAdapters(root: string) {
  const models: ValdiModel[] = [];
  for (const name of new Set(serviceInputs.map(input => input.module))) {
    const dir = path.join(root, 'valdi/modules', name);
    const sourceEntries = serviceInputs.filter(input => input.module === name).map(input => path.join(dir, input.file));
    const module: ValdiModule = { name, dir, generatedDirs: [], sourceEntries };
    const config = ts.readConfigFile(path.join(dir, 'tsconfig.json'), ts.sys.readFile);
    if (config.error) throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, '\n'));
    const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, dir);
    const program = ts.createProgram(sourceEntries, parsed.options);
    const bundle: BundleInfo = { name, asyncStrictMode: false, iosModuleName: name, iosLanguage: 'objc',
      iosCodegenEnabled: true, androidCodegenEnabled: true, cppCodegenEnabled: true,
      androidDefaultClassPath: 'com.snap.modules', cppDefaultClassPrefix: 'snap::valdi_modules::', cppImportPathPrefix: 'valdi_modules/' };
    const fail = (message: string) => { throw new Error(message); };
    const items = processAnnotations(dumpAllSymbols(module, program, fail), bundle, fail);
    if (items.errors.length) throw new Error(items.errors.map(error => error.message).join('\n'));
    for (const item of items.items) if (item.kind === 'exportedType' && item.exportedType.kind === 'valdiModel') models.push(item.exportedType.model);
  }
  const modelFor = (name: string) => {
    const found = models.find(model => model.cppType?.declaration.name === name);
    if (!found) throw new Error(`Missing annotated model ${name}`);
    return found;
  };
  const preamble = '// Generated by tools/valdi-rolldown/harmony-service-adapters.ts. DO NOT EDIT.\n';
  let header = preamble + '#pragma once\n#include "PlatformServicePort.hpp"\n#include "valdi_modules/bluetooth/bluetooth.hpp"\n#include "valdi_modules/app_pages/app_pages.hpp"\nnamespace ValdiHarmony::Platform {\n';
  let source = preamble + '#include "PlatformServiceAdapters.hpp"\n#include "PlatformServiceInterface.hpp"\nnamespace ValdiHarmony::Platform {\n';
  const manifest: { service: string; host: string; methods: string[]; events: string[] }[] = [];
  for (const input of serviceInputs) {
    const model = modelFor(input.host);
    if (!model.exportAsInterface || !model.cppType) throw new Error(`Host ${input.host} must be ExportProxy`);
    const cpp = cppFullTypeName(model.cppType.declaration);
    const generator = new CppCodeGenerator(CppNamespace.root, '', new CppCodeGeneratorSingleNamespaceResolver(CppNamespace.root));
    const allocator = propertyNameAllocatorForCpp(), className = `${input.host}Adapter`;
    const methods: string[] = [], bindings: string[] = [];
    let eventNames: string[] = [], eventsClass = 'nullptr';
    header += `const ServiceDescriptor& ${input.service}Descriptor();\nclass ${className} final : public ${cpp} {\npublic:\n  explicit ${className}(std::weak_ptr<ServicePort> port) : _port(std::move(port)) {}\n`;
    for (const [index, property] of model.properties.entries()) {
      if (property.type.kind !== 'function') throw new Error(`Non-method ${property.name}`);
      const parsed = generator.getTypeParser(property.type, [property.name], allocator).method;
      if (!parsed) throw new Error(`Missing C++ method ${property.name}`);
      const returnType = parsed.returnTypeNameResolver.resolve(CppNamespace.root);
      const params = parsed.parameters.map(param => `${param.typeNameResolver.resolve(CppNamespace.root)} ${param.name}`).join(', ');
      const args = parsed.parameters.map(param => param.name).join(', ');
      header += `  ${returnType} ${property.name}(${params}) final;\n`;
      source += `${returnType} ${className}::${property.name}(${params}) {\n`;
      if (property.type.returnType.kind === 'promise') {
        const result = generator.getTypeParser(property.type.returnType.typeArgument, [property.name, 'Result'], allocator).typeNameResolver.resolve(CppNamespace.root);
        source += `  return invokeFuture<${result}>(_port, ${input.service}Descriptor().methods[${methods.length}]${args ? ', ' + args : ''});\n`;
        methods.push(property.name); bindings.push(`{${index}, "${property.name}"}`);
      } else if (property.name === 'setEvents' && property.type.returnType.kind === 'void') {
        const eventsType = property.type.parameters[0].type;
        if (eventsType.kind !== 'object' || !eventsType.mapping.cppType) throw new Error('Expected events model');
        eventsClass = `${cppFullTypeName(eventsType.mapping.cppType.declaration)}::getRegisteredClass()`;
        const events = models.find(model => model.tsType === eventsType.mapping.tsType);
        if (!events) throw new Error('Missing annotated events model');
        eventNames = events.properties.map(property => property.name);
        source += `  installTypedEvents(_port, *${input.service}Descriptor().events, ${args});\n`;
      } else throw new Error(`Unsupported method ${property.name}`);
      source += '}\n';
    }
    header += 'private:\n  std::weak_ptr<ServicePort> _port;\n};\n';
    source += `const ServiceDescriptor& ${input.service}Descriptor() {\n  static const auto descriptor = makeServiceDescriptor("${input.service}", ${cpp}::getRegisteredClass(),\n    {${bindings.join(', ')}}, ${eventsClass});\n  return descriptor;\n}\n`;
    manifest.push({ service: input.service, host: input.host, methods, events: eventNames });
  }
  header += 'std::array<const ServiceDescriptor*, 4> serviceDescriptors();\nclass ServiceInterfaces {\npublic:\n  explicit ServiceInterfaces(std::weak_ptr<ServicePort> port);\n';
  for (const input of serviceInputs) header += `  const Valdi::Ref<${cppFullTypeName(modelFor(input.host).cppType!.declaration)}>& ${input.service}() const { return _${input.service}; }\n  Valdi::Value ${input.service}Value() const;\n`;
  header += 'private:\n';
  for (const input of serviceInputs) header += `  Valdi::Ref<${cppFullTypeName(modelFor(input.host).cppType!.declaration)}> _${input.service};\n`;
  header += '};\n} // namespace ValdiHarmony::Platform\n';
  source += `std::array<const ServiceDescriptor*, 4> serviceDescriptors() { return {${serviceInputs.map(input => `&${input.service}Descriptor()`).join(', ')}}; }\n`;
  source += `ServiceInterfaces::ServiceInterfaces(std::weak_ptr<ServicePort> port)\n  : ${serviceInputs.map(input => `_${input.service}(Valdi::makeShared<${input.host}Adapter>(port))`).join(',\n    ')} {}\n`;
  for (const input of serviceInputs) source += `Valdi::Value ServiceInterfaces::${input.service}Value() const { return interfaceValue(_${input.service}); }\n`;
  source += '} // namespace ValdiHarmony::Platform\n';
  return { files: new Map([['PlatformServiceAdapters.hpp', header], ['PlatformServiceAdapters.cpp', source]]), manifest };
}
export function checkServiceAdapters(output: string, files: ReadonlyMap<string, string>): void {
  for (const [name, expected] of files) {
    const file = path.join(output, name);
    if (!existsSync(file) || readFileSync(file, 'utf8') !== expected)
      throw new Error(`Stale or missing generated adapter: ${file}; regenerate without --check`);
  }
}
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const index = process.argv.indexOf('--out');
  if (index < 0 || !process.argv[index + 1]) throw new Error('Explicit --out adapter-only directory required');
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..'), output = path.resolve(process.argv[index + 1]);
  const generated = generateServiceAdapters(root);
  const check = process.argv.includes('--check');
  if (check) checkServiceAdapters(output, generated.files);
  else {
    mkdirSync(output, { recursive: true });
    for (const [name, content] of generated.files) writeFileSync(path.join(output, name), content);
  }
  console.log(`${check ? 'Checked' : 'Generated'} ${generated.manifest.reduce((n, item) => n + item.methods.length, 0)} Future methods and ${generated.manifest.reduce((n, item) => n + item.events.length, 0)} events`);
}
