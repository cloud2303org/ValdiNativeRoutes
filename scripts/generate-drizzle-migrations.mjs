#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const folder = path.join(root, 'valdi/drizzle');
const output = path.join(root, 'valdi/modules/app_pages/src/database/generated-migrations.ts');
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: generate-drizzle-migrations.mjs [--check]');
const journal = JSON.parse(await readFile(path.join(folder, 'meta/_journal.json'), 'utf8'));
if (journal.version !== '7' || journal.dialect !== 'sqlite' || !Array.isArray(journal.entries) || !journal.entries.length) {
  throw new Error('Expected a nonempty Drizzle Kit SQLite v7 journal');
}

const tags = new Set();
let previousWhen = -1;
const entries = [];
for (const entry of journal.entries) {
  if (entry.idx !== entries.length || entry.version !== '6' || !Number.isSafeInteger(entry.when) ||
      entry.when <= previousWhen || entry.breakpoints !== true ||
      typeof entry.tag !== 'string' || !/^\d{4}_[a-zA-Z0-9_-]+$/.test(entry.tag) || tags.has(entry.tag)) {
    throw new Error(`Invalid migration journal entry at index ${entries.length}`);
  }
  tags.add(entry.tag);
  previousWhen = entry.when;
  const sql = await readFile(path.join(folder, `${entry.tag}.sql`), 'utf8');
  if (!sql.trim()) throw new Error(`Empty migration ${entry.tag}`);
  // Exactly the delimiter used by drizzle-orm/readMigrationFiles. Semicolons can appear in literals/triggers.
  const statements = sql.split('--> statement-breakpoint');
  entries.push({
    idx: entry.idx,
    tag: entry.tag,
    when: entry.when,
    hash: createHash('sha256').update(sql).digest('hex'),
    statements,
  });
}

const source = `// Generated by scripts/generate-drizzle-migrations.mjs. Do not edit.
// SHA256 covers each complete Kit SQL file; statement chunks retain their exact bytes.
import type { AppMigration } from './migrations';

export const APP_MIGRATIONS: readonly AppMigration[] = ${JSON.stringify(entries, null, 2)};
`;
if (check) {
  const current = await readFile(output, 'utf8').catch(error => {
    if (error.code === 'ENOENT') return undefined;
    throw error;
  });
  if (current !== source) throw new Error('Generated Drizzle migrations are stale. Run node scripts/generate-drizzle-migrations.mjs');
  console.log(`Drizzle migration constants are current (${entries.length} migration${entries.length === 1 ? '' : 's'}).`);
} else {
  await writeFile(output, source);
  console.log(`Generated ${path.relative(root, output)} (${entries.length} migration${entries.length === 1 ? '' : 's'}).`);
}
