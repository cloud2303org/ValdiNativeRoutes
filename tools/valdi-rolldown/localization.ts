import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import type { ValdiModule } from './valdiTs';

export interface LocalizedStrings {
  /** Module-relative JSON archive paths, also passed to the official Inline resolver. */
  entries: Map<string, Buffer>;
  generatedFile: string;
  hash: string;
}

const GENERATED_HEADER = '// Generated by valdi-rolldown/localization.ts. Do not edit.\n';
const HASH_COMMENT = /\n\/\/ valdi-localization-sha256: [a-f0-9]{64}\n$/;

interface Parameter {
  name: string;
  type: 'string' | 'number';
}

interface Message {
  parameters: Parameter[];
}

// Matches valdi_core/src/utils/StringUtils.toCamelCase. For the documented
// lower camelCase / snake_case keys, this also matches the official compiler.
function camelCase(key: string): string {
  return key.split('_').filter(Boolean).map((part, index) =>
    index ? part[0].toUpperCase() + part.slice(1) : part,
  ).join('');
}

function fail(file: string, key: string, message: string): never {
  throw new Error(`${file}: key ${JSON.stringify(key)}: ${message}`);
}

function parameters(message: string, file: string, key: string): Parameter[] {
  const result: Parameter[] = [];
  // TypeScriptStringsModuleGenerator uses (\{([\w_]+)(%.*?)?\}).
  // Inline replaces *every* brace pair by its occurrence index, so malformed
  // pairs cannot safely be left as literal text.
  const token = /\{([a-zA-Z0-9_]+)(%[^{}]*?)?\}/g;
  let offset = 0;
  for (const match of message.matchAll(token)) {
    if (/[{}]/.test(message.slice(offset, match.index))) {
      fail(file, key, 'invalid template placeholder; expected {name}, {name%s}, or {name%d}');
    }
    const format = match[2];
    if (format !== undefined && format !== '%s' && format !== '%d') {
      fail(file, key, `unsupported template format ${JSON.stringify(format)}`);
    }
    result.push({ name: match[1], type: format === '%d' ? 'number' : 'string' });
    offset = match.index! + match[0].length;
  }
  if (/[{}]/.test(message.slice(offset))) {
    fail(file, key, 'invalid template placeholder; expected {name}, {name%s}, or {name%d}');
  }
  return result;
}

function parse(file: string, bytes: Buffer): Map<string, Message> {
  let json: unknown;
  try {
    json = JSON.parse(bytes.toString('utf8'));
  } catch (error) {
    throw new Error(`${file}: invalid JSON: ${(error as Error).message}`);
  }
  if (!json || typeof json !== 'object' || Array.isArray(json)) {
    throw new Error(`${file}: expected a JSON object of string records`);
  }
  const messages = new Map<string, Message>();
  for (const key of Object.keys(json).sort()) {
    // The official compiler ignores this localization-service annotation.
    if (key === 'l10nsvc') continue;
    const record = (json as Record<string, unknown>)[key];
    if (!record || typeof record !== 'object' || Array.isArray(record) ||
        typeof (record as Record<string, unknown>).defaultMessage !== 'string') {
      fail(file, key, 'expected a record with a string defaultMessage');
    }
    messages.set(key, {
      parameters: parameters((record as { defaultMessage: string }).defaultMessage, file, key),
    });
  }
  return messages;
}

/**
 * Read conventional strings/strings-*.json and generate src/Strings.ts underneath
 * generatedDir. Include generatedDir in module.generatedDirs before compiling.
 * The module's own sources are never overwritten. No strings means no output,
 * except removal of a stale file carrying this helper's ownership header.
 */
export function prepareStrings(module: ValdiModule, generatedDir: string): LocalizedStrings | undefined {
  const directory = path.join(module.dir, 'strings');
  const files = existsSync(directory)
    ? readdirSync(directory).filter(file => /^strings-.*\.json$/.test(file)).sort((a, b) => {
      const left = a.slice('strings-'.length, -'.json'.length);
      const right = b.slice('strings-'.length, -'.json'.length);
      return left < right ? -1 : left > right ? 1 : 0;
    })
    : [];
  const generatedFile = path.join(generatedDir, 'src/Strings.ts');
  const previous = existsSync(generatedFile) ? readFileSync(generatedFile, 'utf8') : undefined;
  if (!files.length) {
    if (previous?.startsWith(GENERATED_HEADER)) unlinkSync(generatedFile);
    return undefined;
  }
  for (const relative of ['src/Strings.ts', 'src/Strings.d.ts']) {
    const file = path.join(module.dir, relative);
    if (existsSync(file)) throw new Error(`${file}: localization conflicts with module-owned Strings source`);
  }
  if (previous !== undefined && !previous.startsWith(GENERATED_HEADER)) {
    throw new Error(`${generatedFile}: localization refuses to overwrite a file it does not own`);
  }
  if (!files.includes('strings-en.json')) {
    throw new Error(`${directory}: missing required English fallback strings-en.json`);
  }

  const entries = new Map<string, Buffer>();
  const messagesByFile = new Map<string, Map<string, Message>>();
  const languages: string[] = [];
  for (const file of files) {
    const language = file.slice('strings-'.length, -'.json'.length);
    // Locale.parse uses hyphen-separated language, script, and region components.
    if (!/^[a-zA-Z]{2,8}(?:-[a-zA-Z0-9]{1,8}){0,2}$/.test(language)) {
      throw new Error(`${path.join(directory, file)}: invalid locale filename; use strings-<language[-region]>.json`);
    }
    if (languages.some(existing => existing.toLowerCase() === language.toLowerCase())) {
      throw new Error(`${path.join(directory, file)}: duplicate locale ${language}`);
    }
    languages.push(language);
    const bytes = readFileSync(path.join(directory, file));
    messagesByFile.set(file, parse(path.join(directory, file), bytes));
    // Archive paths always use '/', including on Windows.
    entries.set(`strings/${file}`, bytes);
  }
  const english = messagesByFile.get('strings-en.json')!;
  const names = new Map<string, string>();
  for (const [key, message] of english) {
    const file = path.join(directory, 'strings-en.json');
    const name = camelCase(key);
    if (!name) fail(file, key, 'key must produce a nonempty camelCase accessor');
    const other = names.get(name);
    if (other !== undefined) fail(file, key, `duplicate camelCase accessor ${JSON.stringify(name)} from ${JSON.stringify(other)}`);
    names.set(name, key);
    for (const [translationFile, translations] of messagesByFile) {
      const translation = translations.get(key);
      // Preserve official missing-key behavior: the resolver returns the key.
      if (!translation || translationFile === 'strings-en.json') continue;
      if (translation.parameters.length !== message.parameters.length ||
          translation.parameters.some((parameter, index) =>
            parameter.name !== message.parameters[index].name || parameter.type !== message.parameters[index].type)) {
        fail(path.join(directory, translationFile), key,
          'template parameters must match English names, types, and occurrence order; the Inline runtime substitutes by position');
      }
    }
  }

  const keys = [...english.keys()];
  const interfaceLines = keys.map(key => {
    const args = english.get(key)!.parameters.map((parameter, index) => `arg${index}: ${parameter.type}`);
    return `  ${JSON.stringify(camelCase(key))}(${args.join(', ')}): string;`;
  });
  const types = keys.map(key => {
    const params = english.get(key)!.parameters;
    return params.length ? `[${params.map(parameter => parameter.type === 'number' ? 1 : 0).join(', ')}]` : 'undefined';
  });
  const source = GENERATED_HEADER +
    `import { buildInlineModule } from 'valdi_core/src/LocalizableStrings';\n\n` +
    `export interface Strings {\n${interfaceLines.join('\n')}\n}\n\n` +
    `const strings = buildInlineModule(\n` +
    `  ${JSON.stringify(module.name)},\n` +
    `  ${JSON.stringify(keys)},\n` +
    `  [${types.join(', ')}],\n` +
    `  ${JSON.stringify(languages)},\n` +
    `  ${JSON.stringify([...entries.keys()])},\n` +
    `) as unknown as Strings;\n\nexport default strings;\n`;
  // Avoid changing source mtime (and TS versions) for JSON-only edits.
  if (source !== previous) {
    mkdirSync(path.dirname(generatedFile), { recursive: true });
    writeFileSync(generatedFile, source);
  }
  const hash = createHash('sha256');
  for (const [file, bytes] of entries) hash.update(file).update('\0').update(bytes).update('\0');
  return { entries, generatedFile, hash: hash.digest('hex') };
}

/**
 * Call after compiling, before bytecode/source-map wrapping and dev comparisons.
 * The JS comment makes JSON-only edits visible to dev's JS cache comparison even
 * when the generated TS and compiled JS are otherwise identical.
 */
export function addStringEntries(entries: Map<string, Buffer>, strings: LocalizedStrings | undefined): void {
  if (!strings) return;
  const file = 'src/Strings.js';
  const javascript = entries.get(file);
  if (!javascript) throw new Error(`${strings.generatedFile}: compiled ${file} is missing; include the generated directory before compiling`);
  for (const [name, bytes] of strings.entries) entries.set(name, bytes);
  const source = javascript.toString('utf8').replace(HASH_COMMENT, '');
  entries.set(file, Buffer.from(`${source}\n// valdi-localization-sha256: ${strings.hash}\n`));
}
