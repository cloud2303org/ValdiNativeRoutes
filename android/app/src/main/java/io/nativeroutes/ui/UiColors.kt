fun uiColors(): UiColors = when (LocalUiAppearance.current ?: if (isSystemInDarkTheme()) UiAppearance.Dark else UiAppearance.Light) {
    UiAppearance.Light -> lightColors
    UiAppearance.Dark -> darkColors
}
